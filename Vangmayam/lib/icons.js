export const icon = (name, size = 18) =>
  `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name]}</svg>`;

/** Fill every [data-icon] element with its SVG once. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    if (el.dataset.ready) return;
    el.dataset.ready = '1';
    const small = el.classList.contains('pill') || el.parentElement?.classList.contains('pill') || el.classList.contains('sm');
    el.insertAdjacentHTML('afterbegin', icon(el.dataset.icon, small ? 15 : 18));
  });
}
